/* ---------- schedule helpers ---------- */

type Span = [string, string] | null;
type Week = [Span, Span, Span, Span, Span, Span, Span];

function hoursFrom(spans: Week): OperatingHour[] {
  return spans.map((span, i) =>
    span
      ? {
          dayOfWeek: i + 1,
          openTime: span[0],
          closeTime: span[1],
          isClosed: false,
        }
      : { dayOfWeek: i + 1, openTime: null, closeTime: null, isClosed: true },
  );
}

const daily = (o: string, c: string): Week => [
  [o, c],
  [o, c],
  [o, c],
  [o, c],
  [o, c],
  [o, c],
  [o, c],
];
const weekAndSat = (o: string, c: string, so: string, sc: string): Week => [
  [o, c],
  [o, c],
  [o, c],
  [o, c],
  [o, c],
  [so, sc],
  null,
];
const nonStop: Week = daily("00:00", "23:59");

